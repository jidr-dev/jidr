import XCTest

/// Names for `XCUIElement.ElementType`, as the Swift case names
/// (`staticText`, `button`, …). Unknown raw values read `other(<n>)`.
enum ElementTypes {
    static func name(_ type: XCUIElement.ElementType) -> String {
        let raw = Int(type.rawValue)
        return raw >= 0 && raw < names.count ? names[raw] : "other(\(raw))"
    }

